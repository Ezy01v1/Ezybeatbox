/**
 * Generates the Rive scenes for the Boom Bap streetwear characters:
 * assets/rive/<role>/scene.rml, from src/visuals/streetwear/art.ts and the pack's role colors.
 *
 *   npm run rive:streetwear               # write the six scene.rml files
 *   npm run rive:streetwear -- --verify   # also compile each one with the Rive CLI
 *   npm run rive:streetwear -- --publish  # also write public/packs/boom-bap-01/<role>.riv
 *   npm run rive:streetwear -- --previews # also render PNG previews + gallery to
 *                                         # docs/design/characters-rive/ (combinable)
 *
 * The rig keeps the ids and state machine the app drives (RiveCharacter.tsx):
 * inputs level / beat / status / muted on the "Performance" state machine.
 * `--publish` needs the Rive CLI signed in (`rive login`, once per PC).
 */
import { spawnSync } from 'node:child_process'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { homedir, tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { CHARACTER_ROLES, type CharacterRole } from '../../src/core/packs/schema'
import {
  BROWS_SVG,
  EYES_SVG,
  QUEUED_MOUTH_SVG,
  SINGING_MOUTH_SVG,
  SMILE_SVG,
  bodySvg,
  headSvg,
  paletteFor,
} from '../../src/visuals/streetwear/art'
import { resetShapeNames, rmlColor, svgToRml } from './svgToRml'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const manifest = JSON.parse(
  readFileSync(join(root, 'public/packs/boom-bap-01/manifest.json'), 'utf8'),
) as { theme: { stage: { background: string }; roles: Record<CharacterRole, string> } }

// ── Rig ────────────────────────────────────────────────────────────────────────────────

/** Ids the state machine keys. 0:20–0:24 and 0:30–0:33 match the original rig. */
const ID = {
  avatar: '0:20',
  pivot: '0:21',
  mouth: '0:22',
  head: '0:23',
  ring: '0:24',
  presence: '0:25',
  eyes: '0:60',
  smile: '0:61',
  queuedMouth: '0:62',
  glow: '0:63',
} as const

/**
 * Artwork space is the original SVG rig (120 wide, y from -6). The artboard shows it from the
 * head down to the hips (y = 152) and clips the legs, so characters stand "behind" the stage
 * edge and fill their slot. The compression pivot sits on the hips.
 */
const WIDTH = 120
const HEIGHT = 158
const HIPS = { x: 60, y: 152 }

const LABELS: Record<CharacterRole, string> = {
  kick: 'Kick',
  snare: 'Snare',
  hihat: 'Hi-hat',
  bass: 'Bass',
  voice: 'Voice',
  fx: 'FX',
}

function keyed(id: string, property: string, value: number): string {
  return `<KeyedObject objectId="${id}"><KeyedProperty property="${property}"><KeyFrameDouble value="${value}"/></KeyedProperty></KeyedObject>`
}

function animation(name: string, id: string, keys: [string, string, number][]): string {
  return `<LinearAnimation name="${name}" id="${id}" duration="1">${keys
    .map(([obj, prop, value]) => keyed(obj, prop, value))
    .join('')}</LinearAnimation>`
}

/** Expression parts per status: [eyes, smile, queued mouth, singing mouth, presence]. */
const EXPRESSIONS = {
  resting: [0, 1, 0, 0, 0.65],
  queued: [1, 0, 1, 0, 1],
  singing: [1, 0, 0, 1, 1],
} as const

function statusKeys(state: keyof typeof EXPRESSIONS, ring: number): [string, string, number][] {
  const [eyes, smile, queued, mouth, presence] = EXPRESSIONS[state]
  return [
    [ID.ring, 'opacity', ring],
    [ID.eyes, 'opacity', eyes],
    [ID.smile, 'opacity', smile],
    [ID.queuedMouth, 'opacity', queued],
    [ID.mouth, 'opacity', mouth],
    [ID.presence, 'opacity', presence],
  ]
}

/** Starts the scene in a given state, over a solid background: only for preview renders. */
export interface PreviewState {
  status: number
  level: number
  background: string
}

export function sceneFor(role: CharacterRole, accent: string, preview?: PreviewState): string {
  resetShapeNames()
  const palette = paletteFor(accent)
  const expression = `
    ${BROWS_SVG}
    <g data-name="Eyes" data-id="${ID.eyes}">${EYES_SVG}</g>
    <g data-name="Smile" data-id="${ID.smile}">${SMILE_SVG}</g>
    <g data-name="Queued mouth" data-id="${ID.queuedMouth}">${QUEUED_MOUTH_SVG}</g>
    ${SINGING_MOUTH_SVG.replace('<ellipse', `<ellipse data-name="Mouth" data-id="${ID.mouth}"`)}`
  const head = svgToRml(headSvg(role, palette, expression))
  const body = svgToRml(bodySvg(role, palette))

  return `<Rive version="1" kind="fragment">
  <!-- Generated by scripts/rive/build-streetwear.ts. Edit the art there, not here. -->
  <Artboard name="${LABELS[role]}" id="0:2" width="${WIDTH}" height="${HEIGHT}" clip="true" styleId="0:3" defaultStateMachineId="0:4">
    <LayoutComponentStyle id="0:3"/>
    <Node name="Avatar" id="${ID.avatar}" y="6">
      <Node name="Presence" id="${ID.presence}">
        <Node name="Compression pivot" id="${ID.pivot}" x="${HIPS.x}" y="${HIPS.y}">
          <Node name="Artwork" x="${-HIPS.x}" y="${-HIPS.y}">
            <Node name="Head bounce" id="${ID.head}">
${head}
            </Node>
${body}
          </Node>
        </Node>
      </Node>
      <Shape name="Glow" id="${ID.glow}" x="60" y="82" opacity="0">
        <Ellipse width="160" height="160" originX="0.5" originY="0.5"/>
        <Fill><RadialGradient startX="0" startY="0" endX="80" endY="0">
          <GradientStop colorValue="${rmlColor(accent, 0.9)}" position="0"/>
          <GradientStop colorValue="${rmlColor(accent, 0)}" position="1"/>
        </RadialGradient></Fill>
      </Shape>
    </Node>
    <Shape name="Queued ring" id="${ID.ring}" x="60" y="80" opacity="0">
      <Ellipse width="108" height="146" originX="0.5" originY="0.5"/>
      <Stroke thickness="2.5" cap="round" join="round"><SolidColor colorValue="${rmlColor(accent)}"/>
        <DashPath><Dash length="6"/><Dash length="6"/></DashPath>
      </Stroke>
    </Shape>
${
  preview
    ? `<Shape name="Preview background" x="${WIDTH / 2}" y="${HEIGHT / 2}">
      <Rectangle width="${WIDTH}" height="${HEIGHT}" originX="0.5" originY="0.5"/>
      <Fill><SolidColor colorValue="${rmlColor(preview.background)}"/></Fill>
    </Shape>`
    : ''
}
    <StateMachine name="Performance" id="0:4">
      <StateMachineNumber name="level" id="0:30"${preview ? ` value="${preview.level}"` : ''}/>
      <StateMachineNumber name="beat" id="0:31"/>
      <StateMachineNumber name="status" id="0:32"${preview ? ` value="${preview.status}"` : ''}/>
      <StateMachineBool name="muted" id="0:33"/>
      <StateMachineLayer name="Meter">
        <AnyState x="200" y="-120"/><ExitState x="400" y="-120"/>
        <EntryState><StateTransition stateToId="0:50"/></EntryState>
        <BlendState1DInput id="0:50" x="200" inputId="0:30">
          <BlendAnimation1D value="0" animationId="0:40"/>
          <BlendAnimation1D value="1" animationId="0:41"/>
        </BlendState1DInput>
      </StateMachineLayer>
      <StateMachineLayer name="Beat">
        <AnyState x="200" y="-120"/><ExitState x="400" y="-120"/>
        <EntryState><StateTransition stateToId="0:51"/></EntryState>
        <BlendState1DInput id="0:51" x="200" inputId="0:31">
          <BlendAnimation1D value="0" animationId="0:43"/>
          <BlendAnimation1D value="1" animationId="0:42"/>
        </BlendState1DInput>
      </StateMachineLayer>
      <StateMachineLayer name="Status">
        <AnyState x="200" y="-120"/><ExitState x="400" y="-120"/>
        <EntryState><StateTransition stateToId="0:52"/></EntryState>
        <BlendState1DInput id="0:52" x="200" inputId="0:32">
          <BlendAnimation1D value="0" animationId="0:44"/>
          <BlendAnimation1D value="1" animationId="0:45"/>
          <BlendAnimation1D value="2" animationId="0:48"/>
        </BlendState1DInput>
      </StateMachineLayer>
      <StateMachineLayer name="Mute">
        <AnyState x="200" y="-120"/><ExitState x="400" y="-120"/>
        <EntryState><StateTransition stateToId="0:53"/></EntryState>
        <AnimationState id="0:53" x="200" animationId="0:47">
          <StateTransition stateToId="0:54"><TransitionBoolCondition inputId="0:33" opValue="equal"/></StateTransition>
        </AnimationState>
        <AnimationState id="0:54" x="400" animationId="0:46">
          <StateTransition stateToId="0:53"><TransitionBoolCondition inputId="0:33" opValue="notEqual"/></StateTransition>
        </AnimationState>
      </StateMachineLayer>
    </StateMachine>
    ${animation('Rest', '0:40', [
      [ID.pivot, 'scaleX', 1],
      [ID.pivot, 'scaleY', 1],
      [ID.mouth, 'scaleX', 1],
      [ID.mouth, 'scaleY', 1],
      [ID.glow, 'opacity', 0],
    ])}
    ${animation('Hit', '0:41', [
      [ID.pivot, 'scaleX', 1.03],
      [ID.pivot, 'scaleY', 0.97],
      [ID.mouth, 'scaleX', 1.5],
      [ID.mouth, 'scaleY', 8],
      [ID.glow, 'opacity', 0.55],
    ])}
    ${animation('On the beat', '0:42', [[ID.head, 'y', -4]])}
    ${animation('Between beats', '0:43', [[ID.head, 'y', 0]])}
    ${animation('Resting', '0:44', statusKeys('resting', 0))}
    ${animation('Queued', '0:45', statusKeys('queued', 0.85))}
    ${animation('Singing', '0:48', statusKeys('singing', 0))}
    ${animation('Muted', '0:46', [[ID.avatar, 'opacity', 0.35]])}
    ${animation('Audible', '0:47', [[ID.avatar, 'opacity', 1]])}
  </Artboard>
</Rive>
`
}

function riveExecutable(): string {
  return process.platform === 'win32' ? join(homedir(), '.rive', 'bin', 'rive.exe') : 'rive'
}

// ── Previews ───────────────────────────────────────────────────────────────────────────

const PREVIEW_DIR = join(root, 'docs', 'design', 'characters-rive')
/** 2× the artboard: sharp on GitHub and phones, small enough to keep the repo light. */
const PREVIEW_SIZE = `${WIDTH * 2}x${HEIGHT * 2}`
const PREVIEW_STATES = {
  cantando: { status: 2, level: 0.6 },
  reposo: { status: 0, level: 0 },
} as const

/**
 * Renders each state with the Rive CLI (no login needed) from a temporary copy of the scene
 * that starts in that state. The CLI cannot set state machine inputs, so the initial values
 * are baked into the copy instead.
 */
function renderPreviews(role: CharacterRole): boolean {
  const work = join(tmpdir(), 'ezybeatbox-rive-preview', role)
  let ok = true
  for (const [state, values] of Object.entries(PREVIEW_STATES)) {
    rmSync(work, { recursive: true, force: true })
    mkdirSync(work, { recursive: true })
    writeFileSync(join(work, 'rive.yaml'), `name: ${role}-${state}\n`)
    writeFileSync(
      join(work, 'scene.rml'),
      sceneFor(role, manifest.theme.roles[role], {
        ...values,
        background: manifest.theme.stage.background,
      }),
    )
    const out = join(PREVIEW_DIR, `${role}-${state}.png`).replaceAll('\\', '/')
    const result = spawnSync(riveExecutable(), [work, '--commands'], {
      encoding: 'utf8',
      input: `viewport ${PREVIEW_SIZE}\nfit contain\nscreenshot ${out}\nquit\n`,
    })
    if (result.status !== 0 || !result.stdout.includes('ok screenshot')) {
      ok = false
      console.log(`  ✗ preview ${role}-${state}\n${result.stdout}${result.stderr}`)
    }
  }
  rmSync(work, { recursive: true, force: true })
  return ok
}

function writeGallery(): void {
  const cells = (state: string) =>
    CHARACTER_ROLES.map(
      (role) => `<img src="${role}-${state}.png" width="120" alt="${LABELS[role]}">`,
    )
  const names = CHARACTER_ROLES.map((role) => LABELS[role])
  const row = (items: string[]) => `| ${items.join(' | ')} |`
  writeFileSync(
    join(PREVIEW_DIR, 'README.md'),
    `# Personajes en Rive: vista previa

Generado por \`npm run rive:streetwear -- --previews\` (no editar a mano). Así se ven los
personajes de Boom Bap **en el juego**, renderizados desde \`assets/rive/<rol>/scene.rml\` sobre el
color del escenario. Los conceptos originales están en [\`../characters-v1/\`](../characters-v1/).

## Cantando

${row(names)}
${row(names.map(() => ':---:'))}
${row(cells('cantando'))}

## En reposo (sin sonido)

${row(names)}
${row(names.map(() => ':---:'))}
${row(cells('reposo'))}

## Cómo actualizarlas

1. Editar el arte en \`src/visuals/streetwear/art.ts\` (o los colores de rol en \`scripts/placeholders/packs.ts\`).
2. \`npm run rive:streetwear -- --previews\` regenera las escenas y estas imágenes (necesita el CLI de Rive, sin iniciar sesión).
3. \`npm run rive:streetwear -- --publish --previews\` además escribe los \`.riv\` del juego (necesita \`rive login\`).
`,
  )
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const previews = process.argv.includes('--previews')
  if (previews) mkdirSync(PREVIEW_DIR, { recursive: true })
  const publish = process.argv.includes('--publish')
  const verify = publish || process.argv.includes('--verify')
  const outputDir = join(root, 'public', 'packs', 'boom-bap-01')
  let failed = false
  for (const role of CHARACTER_ROLES) {
    const dir = join(root, 'assets', 'rive', role)
    writeFileSync(join(dir, 'scene.rml'), sceneFor(role, manifest.theme.roles[role]))
    if (previews && !renderPreviews(role)) failed = true
    if (!verify) {
      console.log(`  ✓ ${role}`)
      continue
    }
    const args = publish ? [dir, '--publish', `--output-dir=${outputDir}`] : [dir, '--verify']
    const result = spawnSync(riveExecutable(), args, { encoding: 'utf8' })
    const ok = result.status === 0
    failed ||= !ok
    console.log(`  ${ok ? '✓' : '✗'} ${role}${ok ? '' : `\n${result.stdout}${result.stderr}`}`)
  }
  if (previews) {
    writeGallery()
    console.log(`  ✓ previews in ${PREVIEW_DIR}`)
  }
  if (failed) process.exit(1)
}
